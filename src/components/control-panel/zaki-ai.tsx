"use client";

import { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { CheckCircle2, CircleDashed, Loader2, XCircle } from "lucide-react";
import { ApiError, apiGet, apiPost } from "@/lib/api-client";
import { useI18n } from "@/lib/i18n";
import { cn } from "@/lib/utils";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { useToast } from "@/components/ui/toast";
import type { ZakiAiState, ZakiAiStatus } from "@/server/services/zaki-ai";

/**
 * «زاكي أي أي» on the owner's screens: a chip («مربوط ✓») and the connect panel. Plain requests, no query cache (the home page is a server
 * page and these two parts ask for their own state, so a slow or missing agent never slows the page). The status is cached for 30 seconds on
 * the server and costs the agent nothing (a list of models, no question).
 */

const STATE_ICON: Record<ZakiAiState | "checking", { icon: typeof CheckCircle2; cls: string }> = {
  connected: { icon: CheckCircle2, cls: "text-ok" },
  not_set: { icon: CircleDashed, cls: "text-fg-muted" },
  unreachable: { icon: XCircle, cls: "text-danger" },
  model_missing: { icon: XCircle, cls: "text-warn" },
  checking: { icon: Loader2, cls: "text-fg-muted animate-spin" },
};

/** The page's chip and its connect panel are two parts that must say the same thing: a new answer is told to every part by this event. */
const SHARED = "zk-zaki-ai-status";

/** The status, asked once when the part appears (and again on `reload`). `null` while it is being asked. */
export function useZakiAiStatus(): { status: ZakiAiStatus | null; reload: (fresh?: boolean) => Promise<void>; set: (next: ZakiAiStatus) => void } {
  const [status, setStatus] = useState<ZakiAiStatus | null>(null);
  const set = useCallback((next: ZakiAiStatus) => {
    setStatus(next);
    window.dispatchEvent(new CustomEvent<ZakiAiStatus>(SHARED, { detail: next }));
  }, []);
  const reload = useCallback(
    async (fresh = false) => {
      try {
        set(await apiGet<ZakiAiStatus>(`/api/control-panel/ai${fresh ? "?fresh=1" : ""}`));
      } catch {
        /* an unanswered question leaves the chip as it was */
      }
    },
    [set],
  );
  useEffect(() => {
    let live = true;
    apiGet<ZakiAiStatus>("/api/control-panel/ai").then(
      (s) => live && setStatus(s),
      () => undefined,
    );
    const heard = (event: Event) => setStatus((event as CustomEvent<ZakiAiStatus>).detail);
    window.addEventListener(SHARED, heard);
    return () => {
      live = false;
      window.removeEventListener(SHARED, heard);
    };
  }, []);
  return { status, reload, set };
}

/** The small chip: «زاكي أي أي: مربوط» with its icon, a link to the connect screen. */
export function ZakiAiChip() {
  const { t } = useI18n();
  const { status } = useZakiAiStatus();
  const state: ZakiAiState | "checking" = status ? status.state : "checking";
  const { icon: Icon, cls } = STATE_ICON[state];
  return (
    <Link
      href="/owner?v=ai"
      data-testid="zaki-ai-chip"
      data-state={state}
      className="inline-flex min-h-11 items-center gap-1.5 rounded-full border border-border bg-surface-1 px-3 text-sm hover:bg-surface-2 md:min-h-9"
    >
      <Icon aria-hidden="true" className={cn("size-4", cls)} />
      <span>{t(`cp.ai.chip.${state}`)}</span>
    </Link>
  );
}

const errorText = (t: (key: string) => string, err: unknown): string => {
  if (err instanceof ApiError) {
    const details = Array.isArray(err.details) ? (err.details as { message?: string }[]) : [];
    for (const d of details) if (d.message && t(d.message) !== d.message) return t(d.message);
    if (err.messageKey && t(err.messageKey) !== err.messageKey) return t(err.messageKey);
  }
  return t("common.error");
};

/**
 * The lines the owner adds to the agent's service (its compose file, under `environment:`), and the name of the key the SERVER makes for them
 * (`SERVICE_PASSWORD_*` is generated by the panel, so this screen never invents or shows a key: the owner copies it from there).
 */
const ENV_LINES = ["- API_SERVER_ENABLED=true", "- API_SERVER_HOST=0.0.0.0", "- API_SERVER_PORT=8642", "- 'API_SERVER_KEY=${SERVICE_PASSWORD_APIKEY}'"] as const;
const KEY_VARIABLE = "SERVICE_PASSWORD_APIKEY";

export function ZakiAiPanel() {
  const { t } = useI18n();
  const { toast } = useToast();
  const router = useRouter();
  const { status, reload, set } = useZakiAiStatus();
  const [url, setUrl] = useState<string | null>(null);
  const [model, setModel] = useState<string | null>(null);
  const [key, setKey] = useState("");
  const [local, setLocal] = useState<boolean | null>(null);
  const [busy, setBusy] = useState<"connect" | "test" | null>(null);

  const form = {
    url: url ?? status?.baseUrl ?? status?.suggested.baseUrl ?? "",
    model: model ?? status?.model ?? status?.suggested.model ?? "",
    local: local ?? status?.confirmedLocal ?? false,
  };

  async function connect() {
    if (busy) return;
    setBusy("connect");
    try {
      const next = await apiPost<ZakiAiStatus>("/api/control-panel/ai", { baseUrl: form.url, model: form.model, confirmLocal: form.local, ...(key.trim() ? { key: key.trim() } : {}) });
      set(next);
      setKey("");
      if (next.state === "connected") toast(t("cp.ai.done_connected"), "success");
      else toast(t("cp.ai.done_failed"), "error");
      router.refresh();
    } catch (err) {
      toast(errorText(t, err), "error");
    } finally {
      setBusy(null);
    }
  }

  async function test() {
    if (busy) return;
    setBusy("test");
    try {
      await reload(true);
    } finally {
      setBusy(null);
    }
  }

  const state: ZakiAiState | "checking" = status ? status.state : "checking";
  const { icon: Icon, cls } = STATE_ICON[state];
  const host = status?.baseUrl ? status.baseUrl.replace(/^https?:\/\//, "") : "";
  const field = "w-full rounded-lg border border-border bg-surface-1 px-3 py-2 text-sm text-fg";

  return (
    <div className="space-y-4" data-testid="zaki-ai-panel" data-state={state}>
      <header>
        <h2 className="text-base font-semibold">{t("cp.ai.title")}</h2>
        <p className="text-xs leading-5 text-fg-muted">{t("cp.ai.intro")}</p>
      </header>

      <section className="rounded-card border border-border bg-surface-1 p-4 shadow-card" aria-live="polite">
        <h3 className="text-sm font-semibold">{t("cp.ai.status")}</h3>
        <p className="mt-2 flex items-center gap-2 text-sm">
          <Icon aria-hidden="true" className={cn("size-5 shrink-0", cls)} />
          <span data-testid="zaki-ai-line">{t(`cp.ai.chip.${state}`)}</span>
        </p>
        {status?.state === "connected" ? (
          <p className="mt-1 text-xs leading-5 text-fg-muted">{t("cp.ai.line_connected", { model: status.model ?? "", host, ms: status.listMs ?? 0 })}</p>
        ) : status && status.baseUrl && status.model ? (
          <p className="mt-1 text-xs leading-5 text-fg-muted">{t("cp.ai.saved_as", { model: status.model, host })}</p>
        ) : status ? (
          <p className="mt-1 text-xs leading-5 text-fg-muted">{t("cp.ai.not_saved")}</p>
        ) : null}
        {status?.reason ? <p className="mt-1 text-sm text-danger">{t(status.reason)}</p> : null}
        {status?.state === "connected" ? (
          <p className="mt-1 text-xs leading-5 text-fg-muted">{status.inUse ? t("cp.ai.line_in_use") : t("cp.ai.line_not_in_use")}</p>
        ) : null}
        {status && !status.assistantOn ? <p className="mt-1 text-xs leading-5 text-warn">{t("cp.ai.assistant_off")}</p> : null}
        {status?.baseUrl ? <p className="mt-1 text-xs leading-5 text-fg-muted">{status.confirmedLocal ? t("cp.ai.privacy_local") : t("cp.ai.privacy_external")}</p> : null}
        <div className="mt-3 flex flex-wrap gap-2">
          <Button type="button" size="sm" variant="secondary" disabled={busy !== null || !status?.baseUrl} onClick={() => void test()}>
            {busy === "test" ? t("cp.ai.connecting") : t("cp.ai.test")}
          </Button>
          {status?.state === "connected" && status.inUse && status.assistantOn ? (
            <Link href="/owner/assistant" className="inline-flex h-10 items-center rounded-lg border border-border bg-surface px-3 text-sm hover:bg-surface-2 md:h-8">
              {t("cp.ai.open_assistant")}
            </Link>
          ) : null}
        </div>
      </section>

      {status?.state !== "connected" ? (
        <section className="rounded-card border border-border bg-surface-1 p-4 shadow-card">
          <h3 className="text-sm font-semibold">{t("cp.ai.steps")}</h3>
          <ol className="mt-2 list-decimal space-y-2 ps-5 text-sm leading-6">
            <li>
              {t("cp.ai.step1")}
              <pre className="mt-2 overflow-x-auto rounded-lg border border-border bg-surface-2 p-3 text-xs leading-6" dir="ltr">
                <code>{ENV_LINES.join("\n")}</code>
              </pre>
              <p className="mt-1 text-xs leading-5 text-fg-muted">{t("cp.ai.env_note")}</p>
            </li>
            <li>
              {t("cp.ai.step2")}
              <pre className="mt-2 overflow-x-auto rounded-lg border border-border bg-surface-2 p-3 text-xs" dir="ltr">
                <code>{KEY_VARIABLE}</code>
              </pre>
            </li>
            <li>{t("cp.ai.step3")}</li>
            <li>{t("cp.ai.step4")}</li>
          </ol>
        </section>
      ) : null}

      <form
        className="space-y-3 rounded-card border border-border bg-surface-1 p-4 shadow-card"
        onSubmit={(e) => {
          e.preventDefault();
          void connect();
        }}
      >
        <label className="block space-y-1 text-xs">
          <span className="font-medium text-fg">{t("cp.ai.f.url")}</span>
          <Input dir="ltr" autoComplete="off" spellCheck={false} value={form.url} onChange={(e) => setUrl(e.target.value)} className={field} />
        </label>
        <label className="block space-y-1 text-xs">
          <span className="font-medium text-fg">{t("cp.ai.f.model")}</span>
          <Input dir="ltr" autoComplete="off" spellCheck={false} value={form.model} onChange={(e) => setModel(e.target.value)} className={field} />
        </label>
        <label className="block space-y-1 text-xs">
          <span className="font-medium text-fg">{t("cp.ai.f.key")}</span>
          <Input dir="ltr" type="password" autoComplete="new-password" spellCheck={false} value={key} onChange={(e) => setKey(e.target.value)} className={field} />
          <span className="block text-fg-muted">{status?.hasKey ? t("cp.ai.f.key_saved", { last4: status.keyLast4 ?? "" }) : t("cp.ai.f.key_hint")}</span>
        </label>
        <label className="flex items-start gap-2 text-sm">
          <input type="checkbox" className="mt-1 size-4" checked={form.local} onChange={(e) => setLocal(e.target.checked)} />
          <span>{t("cp.ai.f.local")}</span>
        </label>
        <div className="rounded-lg border border-warn/40 bg-warn/10 px-3 py-2 text-xs">
          <p className="text-fg">{t("cp.ai.f.local_warn")}</p>
          <p className="mt-0.5 text-fg-muted">{t("cp.ai.f.local_fix")}</p>
        </div>
        <div className="rounded-lg border border-warn/40 bg-warn/10 px-3 py-2 text-xs">
          <p className="text-fg">{t("cp.ai.agent_warn")}</p>
          <p className="mt-0.5 text-fg-muted">{t("cp.ai.agent_fix")}</p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <Button type="submit" disabled={busy !== null || !form.url.trim() || !form.model.trim()}>
            {busy === "connect" ? t("cp.ai.connecting") : t("cp.ai.connect")}
          </Button>
          <Link href="/owner/assistant" className="text-sm text-info underline">
            {t("cp.ai.open_settings")}
          </Link>
        </div>
      </form>
    </div>
  );
}
