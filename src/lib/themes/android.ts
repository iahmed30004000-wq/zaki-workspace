/**
 * THE SITE'S THEMES, WRITTEN FOR THE ANDROID APP (docs/restructure/M2-native-app.md, N0).
 *
 * The native app draws with the same palettes as the site: this renders `palettes.ts` (+ the Arabic names of
 * `ar.theme.json`) as ONE Kotlin file, `android/.../ui/theme/Palettes.kt`. It is generated, never edited by hand:
 *
 *   npx tsx scripts/build-android-palettes.mjs           write the file
 *   npx tsx scripts/build-android-palettes.mjs --check   write nothing; exit 1 if it is stale
 *
 * tests/android-palettes.test.ts fails while the committed file differs from what this renders, so a palette changed
 * on the site is a palette changed on the phone (after the next build). Pure: no React, no DOM, no server imports.
 */
import { COLOR_TOKENS, PALETTES, type ColorToken } from "./palettes";
import { THEME_KEYS, THEMES, DEFAULT_THEME, themeLabelKey, themeMoodKey } from "./registry";

export const ANDROID_PALETTES_FILE = "android/app/src/main/java/io/zakiai/workspace/ui/theme/Palettes.kt";

/** `surface-1` → `surface1`, `bubble-out-fg` → `bubbleOutFg`: a Kotlin property name. */
export function kotlinName(token: string): string {
  return token.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** `#36B5CC` → `0xFF36B5CC` (opaque ARGB). */
export function argb(hex: string): string {
  const m = /^#([0-9A-Fa-f]{6})$/.exec(hex);
  if (!m) throw new Error(`not a #RRGGBB colour: ${hex}`);
  return `0xFF${m[1]!.toUpperCase()}`;
}

function kotlinString(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;
}

/** The Kotlin source. `labels` are the Arabic names and moods by dictionary key (passed in, so this file stays pure). */
export function renderAndroidPalettes(labels: Record<string, string>): string {
  const props = COLOR_TOKENS.map((t: ColorToken) => `    val ${kotlinName(t)}: Color,`).join("\n");
  const themes = THEME_KEYS.map((key) => {
    const colors = PALETTES[key].colors;
    const args = COLOR_TOKENS.map((t) => `        ${kotlinName(t)} = Color(${argb(colors[t])}),`).join("\n");
    const label = labels[themeLabelKey(key)] ?? key;
    const mood = labels[themeMoodKey(key)] ?? "";
    return [
      `    ZkTheme(`,
      `        key = ${kotlinString(key)},`,
      `        label = ${kotlinString(label)},`,
      `        mood = ${kotlinString(mood)},`,
      `        dark = ${THEMES[key].dark},`,
      `        kufiHeadings = ${THEMES[key].headingFont === "reem-kufi"},`,
      `        colors = ZkColors(`,
      args.replace(/^/gm, "    "),
      `        ),`,
      `    ),`,
    ].join("\n");
  }).join("\n");
  return [
    "// GENERATED by scripts/build-android-palettes.mjs from src/lib/themes/palettes.ts — do not edit by hand.",
    "// tests/android-palettes.test.ts fails while this file differs from what the script writes.",
    "package io.zakiai.workspace.ui.theme",
    "",
    "import androidx.compose.runtime.Immutable",
    "import androidx.compose.ui.graphics.Color",
    "",
    "/** Every colour a screen may use, by ROLE (the site's tokens). */",
    "@Immutable",
    "data class ZkColors(",
    props,
    ")",
    "",
    "/** One theme of the site: its key (the same as `User.theme`), its Arabic name and mood, light or dark, and its colours. */",
    "@Immutable",
    "data class ZkTheme(",
    "    val key: String,",
    "    val label: String,",
    "    val mood: String,",
    "    val dark: Boolean,",
    "    val kufiHeadings: Boolean,",
    "    val colors: ZkColors,",
    ")",
    "",
    `const val DEFAULT_THEME_KEY = ${kotlinString(DEFAULT_THEME)}`,
    "",
    "/** The themes in the order the site's picker shows them. */",
    "val ZK_THEMES: List<ZkTheme> = listOf(",
    themes,
    ")",
    "",
    "/** The theme of a key; an unknown or retired key is the default, as on the site (`themeOf`). */",
    "fun themeOf(key: String?): ZkTheme = ZK_THEMES.firstOrNull { it.key == key } ?: ZK_THEMES.first { it.key == DEFAULT_THEME_KEY }",
    "",
  ].join("\n");
}
